/** Bundle the read-only editor while keeping Harness's React instance supplied by its module loader. */
import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';
await build({
  entryPoints: [fileURLToPath(new URL('./client.source.js', import.meta.url))],
  outfile: fileURLToPath(new URL('./client.js', import.meta.url)),
  bundle: true, format: 'iife', target: 'es2022',
  tsconfigRaw: { compilerOptions: { alwaysStrict: true } },
  minifyWhitespace: true, minifySyntax: true, keepNames: true,
  // Escaped literal newlines keep dependency snippets compatible with whitespace gates.
  supported: { 'template-literal': false },
  banner: { js: '// Generated by npm run build. Edit client.source.js and its imported source modules.\n' },
});

await build({
  entryPoints: [fileURLToPath(new URL('./terminal-runtime.js', import.meta.url))],
  outfile: fileURLToPath(new URL('./client.terminal.js', import.meta.url)),
  bundle: true, format: 'cjs', target: 'es2022', minify: true,
  loader: { '.css': 'text' },
  banner: { js: '// Generated by npm run build.\nwindow.__ModuleLoader__.load({id: "@yunlai/dsh-workbench", chunk: "client.terminal.js", factory: () => { var module = {exports:{}}; var exports = module.exports;' },
  footer: { js: 'return module.exports; }});' },
});

/** Validated launch configuration for optional Go, Java and Python language servers. */
import Schema from '@deepseek-ai/schemastery';
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';

export const ServerConfig = Schema.object({
  command: Schema.string().required(),
  args: Schema.array(Schema.string()).default([]),
  env: Schema.dict(Schema.string()).default({}),
  settings: Schema.dict(Schema.any()).default({}),
  initializationOptions: Schema.dict(Schema.any()).default({}),
  waitForJavaReady: Schema.union([Schema.boolean(), Schema.const(null)]).default(null),
});

/** Language-server overrides are trusted deployment configuration, never supplied by a browser request. */
export const Config = Schema.object({
  imagePreviewMaxBytes: Schema.number().step(1).min(1024).max(32 * 1024 * 1024).default(8 * 1024 * 1024),
  debugAdapters: Schema.dict(Schema.object({
    command: Schema.string().required(), args: Schema.array(Schema.string()).default([]),
    env: Schema.dict(Schema.string()).default({}), transport: Schema.union(['stdio', 'tcp']).default('stdio'),
  })).default({}),
  useInstalledDebugAdapters: Schema.boolean().default(true),
  debugTimeoutMs: Schema.number().step(1).min(1000).max(300000).default(30000),
  debugOutputChars: Schema.number().step(1).min(1000).max(1000000).default(65536),
  languageServers: Schema.dict(ServerConfig).default({}),
  useInstalledServers: Schema.boolean().default(true),
  navigationTimeoutMs: Schema.number().step(1).min(1000).max(2147483647).default(120000),
  serverKillGraceMs: Schema.number().step(1).min(1).max(2147483647).default(1500),
});

/** Read validated machine-local adapter commands; absent setup leaves explicit plugin configuration in control. */
export function installedDebugAdapters() {
  let text;
  try { text = readFileSync(new URL('./.tools/debug-adapters.json', import.meta.url), 'utf8'); }
  catch (error) { if (error.code === 'ENOENT') return {}; throw error; }
  return Config({ debugAdapters: JSON.parse(text) }).debugAdapters;
}

/**
 * Load private machine-specific commands generated by the setup script.
 * @returns Validated overrides; no file means the documented PATH/bundled defaults.
 */
export function installedServers() {
  let text;
  try { text = readFileSync(new URL('./.tools/servers.json', import.meta.url), 'utf8'); }
  catch (error) { if (error.code === 'ENOENT') return {}; throw error; }
  return Config({ languageServers: JSON.parse(text) }).languageServers;
}

/**
 * Resolve default launch specifications before server startup.
 * @param overrides - Validated plugin and private setup overrides.
 * @returns Explicit specifications keyed by supported server language.
 */
export function serverSpecifications(overrides) {
  for (const language of Object.keys(overrides)) if (!['go', 'java', 'python'].includes(language)) throw new Error(`unsupported configured language: ${language}`);
  const require = createRequire(import.meta.url);
  const resolved = {
    go: { command: 'gopls', args: [], env: {}, settings: {}, initializationOptions: {}, waitForJavaReady: false },
    java: { command: 'jdtls', args: [], env: { JAVA_TOOL_OPTIONS: '-Djava.import.generatesMetadataFilesAtProjectRoot=false' }, settings: { java: { autobuild: { enabled: false }, import: { generatesMetadataFilesAtProjectRoot: false }, configuration: { updateBuildConfiguration: 'disabled' } } }, initializationOptions: {}, waitForJavaReady: true },
    python: { command: 'node', args: [require.resolve('pyright/langserver.index.js'), '--stdio'], env: {},
      settings: { python: { analysis: { autoSearchPaths: true, diagnosticMode: 'openFilesOnly', typeCheckingMode: 'off' } } }, initializationOptions: {}, waitForJavaReady: false },
  };
  for (const [language, override] of Object.entries(overrides)) {
    const defaults = resolved[language];
    let settings = { ...defaults.settings, ...override.settings };
    if (language === 'python') settings = { ...settings, python: {
      ...defaults.settings.python, ...override.settings.python,
      analysis: { ...defaults.settings.python.analysis, ...override.settings.python?.analysis },
    } };
    if (language === 'java') settings = { ...settings, java: {
      ...override.settings.java,
      autobuild: { enabled: false },
      import: { ...override.settings.java?.import, generatesMetadataFilesAtProjectRoot: false },
      configuration: { ...override.settings.java?.configuration, updateBuildConfiguration: 'disabled' },
    } };
    const env = { ...defaults.env, ...override.env };
    if (language === 'java') env.JAVA_TOOL_OPTIONS = `${env.JAVA_TOOL_OPTIONS} -Djava.import.generatesMetadataFilesAtProjectRoot=false`;
    resolved[language] = { ...defaults, ...override, env, settings,
      waitForJavaReady: override.waitForJavaReady ?? defaults.waitForJavaReady };
  }
  return resolved;
}
